#!/usr/bin/env python3
"""Pack the printed-part STLs into docs/setup/assembly/models.js for the guide.

The interactive guide (index.html) renders the *real* meshes from cad/stl/,
so the pictures can never drift from the parts you print. Browsers refuse
fetch() on file:// URLs, so instead of loading the STLs at runtime the
meshes are packed into one classic <script> file: vertices de-duplicated,
positions quantised to 16 bit over each part's bounding box (≈ 0.003 mm
resolution), base64-encoded. Megabytes of ASCII STL become a few hundred
kilobytes of JS, and the guide opens straight from disk.

    python3 docs/setup/assembly/build_models.py

Requires: numpy-stl   (pip install numpy-stl)
Re-run after ./cad/render_all.sh whenever a part changes.
"""
from __future__ import annotations

import base64
import json
import os

import numpy as np
from stl import mesh as stlmesh

HERE = os.path.dirname(os.path.abspath(__file__))
STL_DIR = os.path.join(HERE, "..", "..", "..", "cad", "stl")
OUT = os.path.join(HERE, "models.js")

# name -> stl file. The enclosure is a single body, so nothing here needs
# splitting before it is packed.
PARTS: dict[str, str] = {
    "base_housing":      "base_housing.stl",
    "lid":               "lid.stl",
    "led_diffuser_ring": "led_diffuser_ring.stl",
    "shelf":             "shelf.stl",
    "battery_tray":      "battery_tray.stl",
}


def pack(fname: str) -> dict:
    tris = stlmesh.Mesh.from_file(os.path.join(STL_DIR, fname)).vectors.astype(np.float64)
    flat = np.round(tris.reshape(-1, 3), 4)
    verts, inv = np.unique(flat, axis=0, return_inverse=True)
    inv = inv.reshape(-1)
    lo, hi = verts.min(axis=0), verts.max(axis=0)
    span = np.where(hi - lo > 1e-9, hi - lo, 1.0)
    q = np.round((verts - lo) / span * 65535.0).astype("<u2")
    idx = inv.astype("<u2" if len(verts) < 65536 else "<u4")

    return {
        "min": [round(float(v), 4) for v in lo],
        "max": [round(float(v), 4) for v in hi],
        "nv": int(len(verts)),
        "nt": int(len(tris)),
        "i32": bool(idx.dtype == np.dtype("<u4")),
        "v": base64.b64encode(q.tobytes()).decode("ascii"),
        "i": base64.b64encode(idx.tobytes()).decode("ascii"),
    }


def main() -> None:
    models = {}
    for name, fname in PARTS.items():
        models[name] = pack(fname)
        print(f"{name:20s} {models[name]['nt']:6d} tris  {models[name]['nv']:6d} verts")
    body = json.dumps(models, separators=(",", ":"))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by build_models.py from cad/stl/ — do not edit by hand.\n")
        f.write("window.SPORTCAM_MODELS=" + body + ";\n")
    print(f"wrote {os.path.relpath(OUT)}  ({os.path.getsize(OUT) / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
